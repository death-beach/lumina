// ─────────────────────────────────────────────────────────────────────────────
// Lumina Test Reset Script
// Run with: npm run reset-test
// ─────────────────────────────────────────────────────────────────────────────

import { writeFileSync, readdirSync, unlinkSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");

const RESET = "\x1b[0m";
const GREEN = "\x1b[32m";

function print(msg = "") {
  console.log(msg);
}

function success(msg) {
  print(`${GREEN}✓ ${msg}${RESET}`);
}

// ── Reset lumina.config.ts ───────────────────────────────────────────────────
const baselineConfig = `// lumina.config.ts
// Generated by npm run setup — edit freely.

import type { LuminaConfig } from "@/lib/config";

const config: LuminaConfig = {
  artist: {
    name: "Artist Name",
  },

  album: {
    title: "Title",
  },

  theme: {
    accentColor: "#a78bfa",
    backgroundColor: "#080810",
    blurIntensity: "medium",
    fontDisplay: "inter",
  },

  tracks: [
    {
      id: "track-01",
      title: "track one",
      src: "/tracks/track1.mp3",
      visual: {
        type: "reactive",
        scene: "translation",
      },
    },
    {
      id: "track-02",
      title: "track two",
      src: "/tracks/track2.mp3",
      visual: {
        type: "reactive",
        scene: "particles",
      },
    }
  ],

  features: {
    showPlaylist: true,
    autoplayNext: true,
  },
};

export default config;
`;

const configPath = join(ROOT, "lumina.config.ts");
writeFileSync(configPath, baselineConfig, "utf-8");
success("lumina.config.ts reset to baseline");

// ── Clean up public/lyrics/ ──────────────────────────────────────────────────
const lyricsDir = join(ROOT, "public", "lyrics");
if (existsSync(lyricsDir)) {
  const files = readdirSync(lyricsDir);
  for (const file of files) {
    if ((file.endsWith(".lrc") || file.endsWith(".txt")) && file !== ".gitkeep") {
      unlinkSync(join(lyricsDir, file));
      success(`Removed ${file}`);
    }
  }
}

// ── Clean up public/tracks/ ──────────────────────────────────────────────────
const tracksDir = join(ROOT, "public", "tracks");
if (existsSync(tracksDir)) {
  const files = readdirSync(tracksDir);
  for (const file of files) {
    if (file !== ".gitkeep") {
      unlinkSync(join(tracksDir, file));
      success(`Removed ${file}`);
    }
  }
}

// ── Clean up public/videos/ ──────────────────────────────────────────────────
const videosDir = join(ROOT, "public", "videos");
if (existsSync(videosDir)) {
  const files = readdirSync(videosDir);
  for (const file of files) {
    if (file.endsWith(".mp4")) {
      unlinkSync(join(videosDir, file));
      success(`Removed ${file}`);
    }
  }
}

print("");
success("Test environment reset complete!");
print("");
print("Baseline state:");
print("  lumina.config.ts: 2 tracks (track-01 with timed lyrics, track-02 no lyrics)");
print("  public/lyrics/: empty");
print("  public/tracks/: empty");
print("  public/videos/: empty");
print("");
